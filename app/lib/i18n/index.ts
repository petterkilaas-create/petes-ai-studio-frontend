export const DICTIONARIES: Readonly<Record<Locale, Dictionary>> = { nb, en };

const NORWEGIAN = new Set(["nb", "no", "nn"]);

/**
 * Spraak fra nettleserens foerstevalg: nb, no og nn (ogsaa med region,
 * f.eks. nb-NO) gir norsk, alt annet engelsk.
 */
export function pickLocale(languages: readonly string[] | null | undefined): Locale {
  const first = languages?.[0];
  if (typeof first !== "string") return "en";
  const primary = first.toLowerCase().split(/[-_]/)[0];
  return NORWEGIAN.has(primary) ? "nb" : "en";
}

/** Tekst for en ui-noekkel. `{navn}` byttes med verdien i `vars`. */
export function t(
  locale: Locale,
  key: UiKey,
  vars?: Record<string, string | number>
): string {
  const text = DICTIONARIES[locale].ui[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match
  );
}

/**
 * Oversatt tekst for en kode fra backend. Ukjent, tom eller manglende kode
 * gir gruppens generiske tekst, aldri krasj. hasOwn: "__proto__" og
 * "toString" skal ikke treffe prototypen.
 */
export function codeText(locale: Locale, group: CodeGroup, code: unknown): string {
  const dict = DICTIONARIES[locale];
  const table = dict.codes[group];
  if (typeof code === "string" && Object.hasOwn(table, code)) {
    return table[code];
  }
  return dict.generic[group];
}

/**
 * Tekst for en feilet bestilling (TG-NEW-185). unsupported_image vises etter
 * grunnen (heic, clap, unreadable, format); ukjent eller manglende grunn gir
 * teksten for ukjent grunn. Andre koder som codeText(..., "orderError", ...).
 * Lages ved visning, saa teksten foelger spraakbytte.
 */
export function orderErrorText(locale: Locale, code: unknown, reason: unknown): string {
  if (code === "unsupported_image") return codeText(locale, "unsupportedImage", reason);
  // TG-NEW-268: teksten etter valget (hint, lagt i reason av submitJob); ukjent gir den generelle.
  if (code === "image_type_hint_not_supported") return codeText(locale, "imageTypeHintNotSupported", reason);
  return codeText(locale, "orderError", code);
}

/**
 * Tekst for en feilet bestilling av Aarstider (TG-NEW-271): kodene som bare
 * gjelder aarstider (og `invalid_order`, som ellers ber om rom og stiler)
 * fra aarstidOrderError; alt annet som orderErrorText.
 */
export function aarstidOrderErrorText(locale: Locale, code: unknown, reason: unknown): string {
  const table = DICTIONARIES[locale].codes.aarstidOrderError;
  if (typeof code === "string" && Object.hasOwn(table, code)) return table[code];
  return orderErrorText(locale, code, reason);
}

/**
 * Tekst for en feilet «Lag i en annen årstid» (Dag 58, POST /v1/jobs/{job_id}/aarstid):
 * kodene som bare gjelder den, fra aarstidBytteError; alt annet (402, 429, 503
 * og resten) som orderErrorText.
 */
export function aarstidBytteErrorText(locale: Locale, code: unknown): string {
  const table = DICTIONARIES[locale].codes.aarstidBytteError;
  if (typeof code === "string" && Object.hasOwn(table, code)) return table[code];
  return orderErrorText(locale, code, null);
}

/**
 * Tekst for et bilde som ikke ble lastet opp til ordren (FE-0, K 2.4).
 * unsupported_image vises etter grunnen: heic, unreadable (FE-2), ellers
 * formatet. Andre koder (image_too_large, assignment_image_limit, network)
 * fra uploadError.
 */
export function uploadErrorText(locale: Locale, code: unknown, reason: unknown): string {
  if (code === "unsupported_image") {
    return codeText(locale, "uploadError", reason === "heic" || reason === "unreadable" ? reason : "format");
  }
  return codeText(locale, "uploadError", code);
}

/** Melding som enten er en ui-noekkel eller en kode fra backend. */
export type Message = { key: UiKey } | { group: CodeGroup; code: unknown };

/** Tekst for en Message: ui-noekkel via t, kode via codeText (aldri krasj). */
export function messageText(locale: Locale, message: Message): string {
  return "key" in message ? t(locale, message.key) : codeText(locale, message.group, message.code);
}
